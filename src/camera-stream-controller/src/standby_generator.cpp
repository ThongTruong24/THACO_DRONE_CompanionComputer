StandbyGenerator::StandbyGenerator(int width, int height, int fps)
    : m_width(width > 0 ? width : 1280),
      m_height(height > 0 ? height : 720),
      m_fps(fps > 0 ? fps : 30),
      m_frame_count(0) {}

void StandbyGenerator::updateConfig(int width, int height, int fps) {
    if (width > 0) m_width = width;
    if (height > 0) m_height = height;
    if (fps > 0) m_fps = fps;
}

void StandbyGenerator::drawChar(uint8_t* buffer, int x, int y, char c, int scale, uint8_t b, uint8_t g, uint8_t r) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t* glyph = &FONT_8X8[(c - 32) * 8];

    for (int row = 0; row < 8; ++row) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (line & (0x80 >> col)) {
                for (int dy = 0; dy < scale; ++dy) {
                    int py = y + row * scale + dy;
                    if (py < 0 || py >= m_height) continue;
                    for (int dx = 0; dx < scale; ++dx) {
                        int px = x + col * scale + dx;
                        if (px < 0 || px >= m_width) continue;
                        size_t idx = (static_cast<size_t>(py) * m_width + px) * 3;
                        buffer[idx + 0] = b;
                        buffer[idx + 1] = g;
                        buffer[idx + 2] = r;
                    }
                }
            }
        }
    }
}

void StandbyGenerator::drawText(uint8_t* buffer, int x, int y, const std::string& text, int scale, uint8_t b, uint8_t g, uint8_t r) {
    int cur_x = x;
    for (char c : text) {
        if (c == '\n') {
            y += 10 * scale;
            cur_x = x;
            continue;
        }
        drawChar(buffer, cur_x, y, c, scale, b, g, r);
        cur_x += 8 * scale;
    }
}

void StandbyGenerator::drawRect(uint8_t* buffer, int x, int y, int w, int h, uint8_t b, uint8_t g, uint8_t r) {
    for (int py = y; py < y + h; ++py) {
        if (py < 0 || py >= m_height) continue;
        for (int px = x; px < x + w; ++px) {
            if (px < 0 || px >= m_width) continue;
            size_t idx = (static_cast<size_t>(py) * m_width + px) * 3;
            buffer[idx + 0] = b;
            buffer[idx + 1] = g;
            buffer[idx + 2] = r;
        }
    }
}

void StandbyGenerator::renderBackground(uint8_t* buffer) {
    // Dark slate gradient (BGR: 35, 20, 15 at top to 20, 10, 8 at bottom)
    for (int y = 0; y < m_height; ++y) {
        float ratio = static_cast<float>(y) / static_cast<float>(m_height);
        uint8_t b = static_cast<uint8_t>(38 - ratio * 15);
        uint8_t g = static_cast<uint8_t>(24 - ratio * 12);
        uint8_t r = static_cast<uint8_t>(18 - ratio * 8);

        size_t row_offset = static_cast<size_t>(y) * m_width * 3;
        for (int x = 0; x < m_width; ++x) {
            buffer[row_offset + x * 3 + 0] = b;
            buffer[row_offset + x * 3 + 1] = g;
            buffer[row_offset + x * 3 + 2] = r;
        }
    }

    // Grid pattern (subtle technical overlay)
    for (int y = 0; y < m_height; y += 40) {
        size_t row_offset = static_cast<size_t>(y) * m_width * 3;
        for (int x = 0; x < m_width; ++x) {
            buffer[row_offset + x * 3 + 0] = std::min(255, buffer[row_offset + x * 3 + 0] + 12);
            buffer[row_offset + x * 3 + 1] = std::min(255, buffer[row_offset + x * 3 + 1] + 12);
            buffer[row_offset + x * 3 + 2] = std::min(255, buffer[row_offset + x * 3 + 2] + 12);
        }
    }
    for (int x = 0; x < m_width; x += 40) {
        for (int y = 0; y < m_height; ++y) {
            size_t idx = (static_cast<size_t>(y) * m_width + x) * 3;
            buffer[idx + 0] = std::min(255, buffer[idx + 0] + 12);
            buffer[idx + 1] = std::min(255, buffer[idx + 1] + 12);
            buffer[idx + 2] = std::min(255, buffer[idx + 2] + 12);
        }
    }
}

void StandbyGenerator::generateFrame(FrameData& out_frame, const std::string& status_message) {
    size_t size = static_cast<size_t>(m_width) * m_height * 3;
    if (out_frame.data.size() != size) {
        out_frame.data.resize(size);
    }
    out_frame.width = m_width;
    out_frame.height = m_height;
    out_frame.format = PixelFormat::BGR8;
    out_frame.frame_number = ++m_frame_count;
    out_frame.timestamp_us = std::chrono::duration_cast<std::chrono::microseconds>(
        std::chrono::steady_clock::now().time_since_epoch()
    ).count();

    uint8_t* buf = out_frame.data.data();
    renderBackground(buf);

    // Banners and Panels
    int panel_w = std::min(m_width - 80, 860);
    int panel_h = 320;
    int panel_x = (m_width - panel_w) / 2;
    int panel_y = (m_height - panel_h) / 2;

    // Dark panel with border
    drawRect(buf, panel_x - 3, panel_y - 3, panel_w + 6, panel_h + 6, 200, 160, 30); // Border Cyan/Blue
    drawRect(buf, panel_x, panel_y, panel_w, panel_h, 30, 20, 18); // Dark Box

    // Title
    std::string title = "DRONE VISION SYSTEM - STANDBY";
    drawText(buf, panel_x + 30, panel_y + 35, title, 3, 240, 240, 240);

    // Status Message
    drawText(buf, panel_x + 30, panel_y + 80, status_message, 2, 80, 200, 255); // Amber/Yellow text

    // Timestamp
    auto now = std::chrono::system_clock::now();
    std::time_t now_c = std::chrono::system_clock::to_time_t(now);
    char time_str[64];
    std::strftime(time_str, sizeof(time_str), "%Y-%m-%d %H:%M:%S UTC", std::gmtime(&now_c));
    std::string time_line = std::string("TIME       : ") + time_str;
    drawText(buf, panel_x + 30, panel_y + 130, time_line, 2, 180, 180, 180);

    // Resolution & FPS
    std::ostringstream res_ss;
    res_ss << "STREAM     : " << m_width << "x" << m_height << " @" << m_fps << " FPS (RTSP READY)";
    drawText(buf, panel_x + 30, panel_y + 165, res_ss.str(), 2, 180, 180, 180);

    // Hot-plug Note
    std::string hp_note = "HOT-PLUG   : CONNECT REALSENSE USB TO ACTIVATE LIVE FEED";
    drawText(buf, panel_x + 30, panel_y + 200, hp_note, 2, 100, 230, 100); // Light Green

    // Blinking Heartbeat Indicator & Spinner
    bool blink = (m_frame_count / (m_fps / 2 > 0 ? m_fps / 2 : 15)) % 2 == 0;
    const char spinner_chars[] = {'|', '/', '-', '\\'};
    char spin_c = spinner_chars[(m_frame_count / (m_fps / 4 > 0 ? m_fps / 4 : 8)) % 4];

    std::string status_box = std::string("[ STANDBY ACTIVE ") + spin_c + " ]";
    if (blink) {
        drawRect(buf, panel_x + 30, panel_y + 245, 240, 36, 0, 140, 230); // Orange/Red beacon
        drawText(buf, panel_x + 40, panel_y + 253, status_box, 2, 255, 255, 255);
    } else {
        drawRect(buf, panel_x + 30, panel_y + 245, 240, 36, 60, 60, 60);
        drawText(buf, panel_x + 40, panel_y + 253, status_box, 2, 180, 180, 180);
    }

    // Moving scan line along the bottom of the panel
    int scan_w = 120;
    int scan_x = panel_x + 300 + (static_cast<int>(m_frame_count * 5) % (panel_w - 320 - scan_w));
    drawRect(buf, scan_x, panel_y + 260, scan_w, 6, 255, 200, 50);
}

